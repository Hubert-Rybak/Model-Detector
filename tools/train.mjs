// Train the naive-Bayes fingerprint from corpus/ and write docs/model.js.
//   node tools/train.mjs [--corpus corpus] [--out docs/model.js] [--min-df 2]
import fs from "node:fs";
import { trainNB, tokenize, nbScore, softmax, analyze } from "../docs/engine.js";
import { loadCorpus } from "./corpus.mjs";

const args = Object.fromEntries(process.argv.slice(2).map((a, i, arr) => a.startsWith("--") ? [a.slice(2), arr[i + 1] && !arr[i + 1].startsWith("--") ? arr[i + 1] : true] : []).filter(Boolean));
const root = args.corpus || "corpus";
const out = args.out || "docs/model.js";
const minDf = Number(args["min-df"] || 2);
const features = args.features || "all";   // all | style | markers

const samples = loadCorpus(root).filter((s) => s.family && s.text.split(/\s+/).length >= 20);
for (const s of samples) s.bag = tokenize(s.text, null, { mode: features });
const byFamily = {}, byModel = {};
for (const s of samples) { byFamily[s.family] = (byFamily[s.family] || 0) + 1; byModel[`${s.family}/${s.model}`] = (byModel[`${s.family}/${s.model}`] || 0) + 1; }
console.log(`samples: ${samples.length}`);
console.log("per family:", byFamily);
console.log("per model:", byModel);

const family = trainNB(samples, { minDf, level: "family" });
const modelsNB = trainNB(samples.filter((s) => s.model), { minDf, level: "model" });
for (const [name, c] of Object.entries(modelsNB.classes)) c.family = samples.find((s) => s.model === name).family;

// Hold-one-prompt-out metrics so the app can show how much to trust each level.
function holdoutGroups() {
  const byPrompt = new Map();
  samples.forEach((s, i) => { const k = s.prompt || `doc${i}`; (byPrompt.get(k) || byPrompt.set(k, []).get(k)).push(i); });
  return [...byPrompt.values()];
}
const evalInfo = { holdout: "prompt", family: null, models: {} };
const groups = holdoutGroups();
if (Object.keys(byFamily).length >= 2) {
  let ok = 0, n = 0;
  for (const g of groups) {
    const train = samples.filter((_, i) => !g.includes(i));
    const m = { features, family: trainNB(train, { minDf, level: "family" }), models: null };
    for (const i of g) { n++; if (analyze(samples[i].text, m).top === samples[i].family) ok++; }
  }
  evalInfo.family = { correct: ok, n, accuracy: Math.round(1000 * ok / Math.max(1, n)) / 1000, chance: Math.round(1000 / Object.keys(byFamily).length) / 1000 };
}
for (const fam of Object.keys(byFamily)) {
  const fs = samples.map((s, i) => [s, i]).filter(([s]) => s.family === fam && s.model);
  const models = new Set(fs.map(([s]) => s.model));
  if (models.size < 2) continue;
  let ok = 0, n = 0;
  for (const g of groups) {
    const train = fs.filter(([, i]) => !g.includes(i)).map(([s]) => s);
    if (!train.length) continue;
    const nb = trainNB(train, { minDf, level: "model" });
    for (const [s, i] of fs) {
      if (!g.includes(i)) continue;
      const sc = nbScore(s.bag, nb);
      if (!sc) continue;
      const pr = softmax(sc.logodds);
      const pred = Object.keys(pr).sort((a, b) => pr[b] - pr[a])[0];
      n++; if (pred === s.model) ok++;
    }
  }
  evalInfo.models[fam] = { correct: ok, n, accuracy: Math.round(1000 * ok / Math.max(1, n)) / 1000, chance: Math.round(1000 / models.size) / 1000, classes: models.size };
}
console.log("hold-out metrics:", JSON.stringify(evalInfo));

const model = {
  version: 1, trained_at: new Date().toISOString(), n_samples: samples.length, per_family: byFamily, per_model: byModel,
  features, family, models: modelsNB, eval: evalInfo,
};
const js = `// Generated by tools/train.mjs on ${model.trained_at} from ${samples.length} samples. Do not edit by hand.\nexport default ${JSON.stringify(model)};\n`;
fs.writeFileSync(out, js);
console.log(`wrote ${out} (${(js.length / 1024).toFixed(0)} kB, vocab ${family.vocab_size})`);
